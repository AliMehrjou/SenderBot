# ============================================================
# ابزار زمان — ساعت ایران (آفست ثابت UTC+3:30)
# ============================================================
def _now_tehran() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc) + _TEHRAN_UTC_OFFSET


def _tehran_date_str() -> str:
    """تاریخ امروز به وقت ایران — برای جلوگیری از ارسال دوباره در همان روز."""
    return _now_tehran().strftime("%Y-%m-%d")


def _seconds_until_target_hour() -> float:
    """فاصله (ثانیه) تا سرِ ساعتِ ارسال به وقت ایران (پیش‌فرض ۹ صبح)."""
    try:
        hour = max(0, min(23, int(config.DAILY_ADS_HOUR)))
    except (TypeError, ValueError):
        hour = 9
    now_t = _now_tehran()
    target = now_t.replace(hour=hour, minute=0, second=0, microsecond=0)
    if now_t >= target:
        target += dt.timedelta(days=1)
    return max(30.0, (target - now_t).total_seconds())


# ============================================================
# ابزار Redis — هر خطا بی‌صدا مدیریت می‌شود (ربات هرگز به‌خاطر
# تبلیغات روزانه نباید از کار بیفتد)
# ============================================================
async def _load_index() -> int:
    try:
        raw = await _get_redis().get(_KEY_INDEX)
        return int(raw) % len(DAILY_ADS) if raw is not None else 0
    except Exception as e:
        logger.warning("Daily ads: خواندن ایندکس از Redis ناموفق (%s) — از پیام اول شروع می‌شود.", e)
        return 0


async def _already_sent_today() -> bool:
    """آیا پیامِ امروز قبلاً ارسال شده؟

    🛡 سیاست ضداسپم:
      • پشتیبان درون‌حافظه‌ای اول چک می‌شود؛
      • اگر Redis در دسترس نباشد → True فرض می‌شود (ارسال‌شده) تا در حالت
        خرابی Redis هرگز اسپم رخ ندهد؛ حداکثر یک پیام در هر ری‌استارت.
    """
    global _memory_last_date
    today = _tehran_date_str()
    if _memory_last_date == today:
        return True
    try:
        val = await _get_redis().get(_KEY_LAST_DATE)
    except Exception as e:
        logger.warning("Daily ads: Redis در دسترس نیست (%s) — برای جلوگیری از اسپم، امروز ارسال‌شده فرض می‌شود.", e)
        return True
    if val == today:
        _memory_last_date = today
        return True
    return False


async def _save_state(next_idx: int) -> None:
    """ثبت تاریخ امروز (ضدارسال) + ایندکس فردا — هم در حافظه هم در Redis."""
    global _memory_last_date
    _memory_last_date = _tehran_date_str()  # حتی اگر Redis قطع باشد، این پروسه اسپم نمی‌کند
    try:
        redis = _get_redis()
        await redis.set(_KEY_INDEX, str(next_idx))
        await redis.set(_KEY_LAST_DATE, _memory_last_date, ex=_DATE_TTL)
    except Exception as e:
        logger.warning("Daily ads: ذخیره وضعیت در Redis ناموفق (%s).", e)


# ============================================================
# مخاطبان — کاربران ربات (ادمین اصلی + ساب‌ادمین‌ها)
# ============================================================
async def _get_recipients() -> list:
    from utils.admin_broadcast import _get_all_admin_ids
    try:
        return await _get_all_admin_ids()
    except Exception as e:
        logger.warning("Daily ads: واکشی ادمین‌ها ناموفق (%s).", e)
        return []


# ============================================================
# ارسال پیامِ امروز (به ترتیب + چرخه‌ای)
# ============================================================
async def _send_today(bot: Bot) -> None:
    if await _already_sent_today():
        return

    recipients = await _get_recipients()
    if not recipients:
        logger.info("Daily ads: کاربری برای ارسال یافت نشد.")
        return

    idx = await _load_index()
    message_text = DAILY_ADS[idx]

    sent = failed = 0
    for uid in recipients:
        try:
            # متن ساده (بدون قالب) — پیام‌های کارفرما متنی خالص هستند
            await bot.send_message(uid, message_text, parse_mode=None)
            sent += 1
        except Exception:
            failed += 1  # بلاک/غیرفعال — رد و ادامه
        await asyncio.sleep(_SEND_INTERVAL)

    # ثبت وضعیت: تاریخ امروز + ایندکسِ فردا (چرخه‌ای: بعد از آخری → اولی)
    next_idx = (idx + 1) % len(DAILY_ADS)
    await _save_state(next_idx)

    logger.info(
        "Daily ads: پیام %d از %d برای %d کاربر ارسال شد (موفق: %d، ناموفق: %d) — فردا: %d",
        idx + 1, len(DAILY_ADS), len(recipients), sent, failed, next_idx + 1,
    )


# ============================================================
# حلقه پس‌زمینه
# ============================================================
async def daily_ads_loop(bot: Bot) -> None:
    """
    تسک پس‌زمینه:
      • اگر ساعتِ رسیده یا گذشته (بعد از ۹) و پیام امروز هنوز نرفته
        → همین حالا ارسال می‌شود (جبرانی — برای مواقعی که ربات ساعت ۹
        خاموش بوده و بعداً روشن شده؛ همان روز پیام از دست نمی‌رود).
      • اگر هنوز به ساعت ۹ نرسیده → می‌خوابد تا سر ساعت ۹.
    """
    if not getattr(config, "DAILY_ADS_ENABLED", True):
        logger.info("Daily ads: قابلیت پیام‌های روزانه خاموش است (DAILY_ADS_ENABLED=false).")
        return

    logger.info(
        "Daily ads: قابلیت فعال است — هر روز ساعت %s به وقت ایران، %d پیام به ترتیب و چرخه‌ای ارسال می‌شود.",
        getattr(config, "DAILY_ADS_HOUR", 9), len(DAILY_ADS),
    )

    while True:
        try:
            # 🩹 ارسال جبرانی: بعد از ساعتِ مقصد و ارسال‌نشده بودنِ پیامِ امروز
            hour = max(0, min(23, int(getattr(config, "DAILY_ADS_HOUR", 9))))
            if _now_tehran().hour >= hour and not await _already_sent_today():
                logger.info("Daily ads: پیامِ امروز هنوز ارسال نشده — ارسال جبرانی همین حالا.")
                await _send_today(bot)
                # ۵ دقیقه (نه ۹۰ ثانیه) — اگر مثلاً کاربری/ادمینی موقتاً در دسترس
                # نبود، این حلقه آزاردهنده/پرلاگ تکرار نشود
                await asyncio.sleep(300)
                continue

            # خواب تا سرِ ساعتِ مقصد (امروز یا فردا — خودکار محاسبه می‌شود)
            wait_seconds = _seconds_until_target_hour()
            logger.info("Daily ads: ارسال بعدی تا %.0f دقیقه دیگر.", wait_seconds / 60)
            await asyncio.sleep(wait_seconds)
            await _send_today(bot)
            # مکث کوتاه تا در محاسبه «تا فردا» همپوشانی رخ ندهد
            await asyncio.sleep(90)
        except asyncio.CancelledError:
            raise
        except Exception:
            logger.exception("Daily ads: خطا در حلقه ارسال روزانه — تلاش مجدد تا ۵ دقیقه دیگر.")
            await asyncio.sleep(300)
